import os
from dotenv import load_dotenv
from openai import OpenAI

# Завантажуємо змінні оточення з .env
load_dotenv()

# 1. Константи для тестування різних платформ
BASE_URL = os.getenv("ODIROUTER_BASE_URL", "https://api.odirouter.ai/v1")
API_KEY = os.getenv("ODIROUTER_API_KEY")
MODEL_NAME = "free-gemini-2.5-flash"  # Зміни на deepseek-v4-flash для тесту JSON

if not API_KEY:
    raise ValueError("⚠️ Помилка: Ключ ODIROUTER_API_KEY не знайдено в .env файлі!")

# 2. Ініціалізація клієнта
client = OpenAI(
    base_url=BASE_URL,
    api_key=API_KEY
)

# 3. Відкалібрований лор та інструкція
system_prompt = """Империя разваливалась – бунты рабов, нехватка казны, внутренние переживания и неудачная война с Дворфами привели к тому, что Империя развалилась на 3 отдельных государства, да и они вскоре были полностью уничтожены. Люди воспользовались слабостью Эльфийской Империи и в 288 году объявили им войну. К тому времени люди были объединены одним перспективным и молодым лидером, по имени – Саниус Секстий. Он смог через дипломатию и внутренние интриги объединить королевства так, чтобы те сохранили независимость. Естественно Империя Эльфов проиграла, а на её осколках возвысилась Империя Людей.
Мир восстанавливался от кровавых войн и восстаний, и расы снова могли передохнуть от постоянных войн, но произошло непредвиденное – вторжение «Демонов» и «Ангелов» в этот мир. Переговоры с ними ничего не дали, а единственной их целью было превратить этот мир в их поле боя. Ангелы смогли воспользоваться государственным строем Горных жителей и подчинили их своей воле. Демоны же, в свою очередь, решили использовать Орков и наделили их жаждой крови. При изучении чуждых нам рас, мы выяснили, что их технологический прогресс был намного выше нашего, а магия была частью каждого Демона и Ангела.
Как будто марионетками они управляли этими расами и использовали в качестве пешек, когда же шла настоящая битва то материк и небеса страдали от гигантских Магических заклинаний, а так-же неописуемой аурой двух сторон конфликта. Вскоре Демоны и Ангелы ушли, но никто точно не может понять почему. Даже сегодня есть некоторые догадки того, почему они просто взяли и ушли – “Проблемы в мирах Ангелов и Демонов”, “Изменения в ситуации”, “Им стало невмоготу продолжать бой”. Они оставили после себя гигантские кратеры и разрушенные биоценозы континента. В будущем, через несколько лет, Людская Империя, как и все остальные страны и государства, смогут находиться в находиться в продолжительном мире. Начнут восстанавливать города и деревни – все начнут новую жизнь.

Эра Восстановления
С тех времён прошло более трёх сотен лет, а Государства с Империей Людей практически не изменили свои территориальные границы. С тех потрясений больше не было больших войн, только мелкие локальные конфликты. Технологический и Магический прогресс сильно изменился с тех пор. Государства пытались сделать всё, что-бы отойти от событий трёхсотлетней давности, и они удачно смогли это сделать. Через 300 лет появляются новые книги и даже исследовательские работы, появляется комитет Имперских Профессоров, а так-же проводятся всевозможные реформы, для улучшения нынешнего положения – но это не значит, что в мире нет никаких проблем. Самыми серьёзными проблемами нашего времени являются: Точечные вспышки чумы и появление в очагах заражения нежити. Голод среди нищих, которых появилось очень много из-за войны. Рост преступности по всему миру. Огромное количество монстров.
Открытие Врата в другие миры, хоть и недолго, но пропустило в наш мир множество чудовищ и всякую нечисть – это и повлияло на восстановление от потрясений, полученных за столетия. На данный момент насчитывается около 40 разных тварей из других миров и более 150 видов мутантов из нашего мира.

Твоя роль — суровый Мастер Игры (ГМ) в этой вселенной. Игрок — бедный путешественник, только что зашедший в зачумленное село на окраине Империи Людей. 

Жесткие правила ответа:
1. НИКАКИХ вступлений, приветствий или выхода из роли.
2. Начинай ответ сразу с художественного описания происходящего.
3. Строгий лимит: ровно 3 предложения.
4. Атмосфера должна быть мрачной. Опиши окружение и одно стартовое событие, требующее реакции игрока."""

user_action = "Я медленно захожу в деревню и присматриваюсь к первому дому который вижу."

# 4. Відправка запиту
print(f"Відправляємо запит до {MODEL_NAME} на {BASE_URL}...")
try:
    response = client.chat.completions.create(
        model=MODEL_NAME,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_action}
        ],
        temperature=0.7,  # 0.7 для художнього тексту. Для тестів JSON став 0.0
        max_tokens=300
    )
    print("\n=== ВІДПОВІДЬ ===")
    print(response.choices[0].message.content)
except Exception as e:
    print(f"\nПомилка: {e}")
